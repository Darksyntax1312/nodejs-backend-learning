  static fetchAll(callback) {
    fs.readFile("NewIdFile.txt", (err, data) => {
      // 1. Handle errors
      if (err) {
        if (err.code === "ENOENT") {
          return callback(null, []);
        }

        return callback(err, null);
      }

      // 2. Handle an empty file
      if (data.length === 0) {
        return callback(null, []);
      }

      // 3. Parse the file's JSON data
      let existingData;

      try {
        existingData = JSON.parse(data.toString());
      } catch (error) {
        return callback(error, null);
      }

      // 4. Make sure the parsed data is an array
      if (!Array.isArray(existingData)) {
        return callback(new Error("Favourite data must be an array"), null);
      }

      // 5. Return the successfully fetched data
      callback(null, existingData);
    });
  }










